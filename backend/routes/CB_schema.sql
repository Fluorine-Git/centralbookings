CREATE DATABASE IF NOT EXISTS centralbookings_db;
USE centralbookings_db;

DROP TABLE IF EXISTS ACTIVITY_BOOKING;
DROP TABLE IF EXISTS ACTIVITY_SCHEDULE;
DROP TABLE IF EXISTS PARTICIPANT;
DROP TABLE IF EXISTS LOCATION;
DROP TABLE IF EXISTS ACTIVITY;
DROP TABLE IF EXISTS ORGANIZER;
DROP TABLE IF EXISTS CONTACT;

CREATE TABLE CONTACT (
    CONTACT_ID             VARCHAR(7)   NOT NULL,
    CONTACT_FIRST_NAME     VARCHAR(100) NOT NULL,
    CONTACT_MIDDLE_INITIAL VARCHAR(2)   NULL,
    CONTACT_LAST_NAME      VARCHAR(100) NOT NULL,
    CONTACT_EMAIL          VARCHAR(100) NOT NULL,
    CONTACT_NUMBER         VARCHAR(11)  NOT NULL,
    PRIMARY KEY (CONTACT_ID)
);

CREATE TABLE ORGANIZER (
    ORGANIZER_ID       VARCHAR(5)   NOT NULL,
    CONTACT_ID         VARCHAR(8)   NOT NULL,
    ORGANIZER_NAME     VARCHAR(255) NOT NULL,
    ORGANIZER_STREET   VARCHAR(255) NOT NULL,
    ORGANIZER_BARANGAY VARCHAR(255) NOT NULL,
    ORGANIZER_CITY     VARCHAR(255) NOT NULL,
    ORGANIZER_PROVINCE VARCHAR(255) NOT NULL,
    ORGANIZER_TYPE     VARCHAR(100) NOT NULL,
    PRIMARY KEY (ORGANIZER_ID),
    CONSTRAINT fk_organizer_contact
        FOREIGN KEY (CONTACT_ID) REFERENCES CONTACT (CONTACT_ID)
);

CREATE TABLE ACTIVITY (
    ACTIVITY_ID           INT          NOT NULL AUTO_INCREMENT,
    ORGANIZER_ID          VARCHAR(5)   NOT NULL,
    ACTIVITY_TITLE        VARCHAR(255) NOT NULL,
    ACTIVITY_DESCRIPTION  VARCHAR(255) NOT NULL,
    EXPECTED_PARTICIPANTS INT          NOT NULL DEFAULT 0,
    PRIMARY KEY (ACTIVITY_ID),
    CONSTRAINT fk_activity_organizer
        FOREIGN KEY (ORGANIZER_ID) REFERENCES ORGANIZER (ORGANIZER_ID),
    CONSTRAINT chk_expected_participants_nonneg
        CHECK (EXPECTED_PARTICIPANTS >= 0)
);

CREATE TABLE LOCATION (
    LOCATION_ID          VARCHAR(6)   NOT NULL,
    LOCATION_BUILDING    VARCHAR(255) NOT NULL,
    LOCATION_ROOM_NUMBER INT          NOT NULL,
    LOCATION_NAME        VARCHAR(255) NOT NULL,
    LOCATION_CAPACITY    INT          NOT NULL DEFAULT 0,
    PRIMARY KEY (LOCATION_ID),
    CONSTRAINT chk_location_capacity_nonneg
        CHECK (LOCATION_CAPACITY >= 0)
);

CREATE TABLE PARTICIPANT (
    ID_NUMBER                  VARCHAR(8)   NOT NULL AUTO_INCREMENT,
    PARTICIPANT_FIRST_NAME     VARCHAR(100) NOT NULL,
    PARTICIPANT_MIDDLE_INITIAL VARCHAR(2)   NULL,
    PARTICIPANT_LAST_NAME      VARCHAR(100) NOT NULL,
    PARTICIPANT_BIRTH_DATE     DATE         NOT NULL,
    PARTICIPANT_DEPARTMENT     VARCHAR(255) NOT NULL,
    PARTICIPANT_TYPE           VARCHAR(100) NOT NULL,
    PRIMARY KEY (ID_NUMBER)
);

CREATE TABLE ACTIVITY_SCHEDULE (
    SCHEDULE_ID          VARCHAR(10)   NOT NULL AUTO_INCREMENT,
    ACTIVITY_ID          INT           NOT NULL,
    LOCATION_ID          VARCHAR(8)    NOT NULL,
    SCHEDULE_DATE        DATE          NOT NULL,
    SCHEDULE_START_TIME  TIME          NOT NULL,
    SCHEDULE_END_TIME    TIME          NOT NULL,
    PRIMARY KEY (SCHEDULE_ID),
    CONSTRAINT fk_schedule_activity
        FOREIGN KEY (ACTIVITY_ID) REFERENCES ACTIVITY (ACTIVITY_ID),
    CONSTRAINT fk_schedule_location
        FOREIGN KEY (LOCATION_ID) REFERENCES LOCATION (LOCATION_ID),
    CONSTRAINT chk_schedule_time_order
        CHECK (SCHEDULE_END_TIME > SCHEDULE_START_TIME)
);

CREATE TABLE ACTIVITY_BOOKING (
    BOOKING_NUMBER VARCHAR(12)  NOT NULL AUTO_INCREMENT,
    SCHEDULE_ID    INT          NOT NULL,
    ID_NUMBER      INT          NOT NULL,
    HAS_ATTENDED   BOOLEAN      NOT NULL DEFAULT FALSE,
    PRIMARY KEY (BOOKING_NUMBER),
    CONSTRAINT fk_booking_schedule
        FOREIGN KEY (SCHEDULE_ID) REFERENCES ACTIVITY_SCHEDULE (SCHEDULE_ID),
    CONSTRAINT fk_booking_participant
        FOREIGN KEY (ID_NUMBER) REFERENCES PARTICIPANT (ID_NUMBER),
    CONSTRAINT uq_booking_schedule_participant
        UNIQUE (SCHEDULE_ID, ID_NUMBER)
);